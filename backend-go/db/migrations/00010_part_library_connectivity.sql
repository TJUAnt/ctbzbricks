CREATE TABLE component_repo.part_collider_definitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_library_version_id uuid NOT NULL REFERENCES component_repo.part_library_versions(id) ON DELETE CASCADE,
    source_collider_id bigint NOT NULL,
    ldraw_part_num text NOT NULL,
    collider_kind text NOT NULL,
    position double precision[] NOT NULL,
    orientation double precision[] NOT NULL,
    half_extents double precision[] NOT NULL,
    raw_params jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (part_library_version_id, source_collider_id),
    CONSTRAINT part_collider_definitions_position_check CHECK (cardinality(position) = 3),
    CONSTRAINT part_collider_definitions_orientation_check CHECK (cardinality(orientation) = 9),
    CONSTRAINT part_collider_definitions_half_extents_check CHECK (
        cardinality(half_extents) = 3
        AND half_extents[1] >= 0
        AND half_extents[2] >= 0
        AND half_extents[3] >= 0
    ),
    CONSTRAINT part_collider_definitions_raw_params_check CHECK (jsonb_typeof(raw_params) = 'object')
);

