UPDATE component_repo.part_library_versions version
SET preview_ready = EXISTS (
        SELECT 1
        FROM component_repo.part_geometries geometry
        WHERE geometry.part_library_version_id = version.id
          AND geometry.geometry_status = 'ready'
    ),
    relation_ready = version.connector_count > 0,
    connector_source_hash = CASE WHEN version.connector_count > 0 THEN version.source_hash END,
    connector_parser_version = CASE WHEN version.connector_count > 0 THEN 'legacy-imported-v1' END;

