import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'src/i18n/catalog.json'), 'utf8'));
const resourceDirectory = path.join(root, `src/i18n/resources/${catalog.sourceLocale}`);
const outputPath = path.join(root, 'src/i18n/generated.ts');
const numericParameters = new Set(['count', 'percent']);

const records = fs.readdirSync(resourceDirectory)
  .filter((file) => file.endsWith('.json'))
  .sort()
  .flatMap((file) => {
    const namespace = path.basename(file, '.json');
    const resources = JSON.parse(fs.readFileSync(path.join(resourceDirectory, file), 'utf8'));
    return Object.entries(resources).map(([key, value]) => ({
      key: `${namespace}:${key}`,
      value: String(value),
    }));
  })
  .sort((left, right) => left.key.localeCompare(right.key));

const keys = records.map(({ key }) => `  | ${JSON.stringify(key)}`).join('\n');
const parameterRecords = records.flatMap(({ key, value }) => {
  const parameters = [...new Set([...value.matchAll(/\{\{\s*([A-Za-z_][A-Za-z0-9_]*)[^}]*\}\}/g)].map((match) => match[1]))];
  if (parameters.length === 0) return [];
  const fields = parameters
    .sort()
    .map((parameter) => `    ${JSON.stringify(parameter)}: ${numericParameters.has(parameter) ? 'number' : 'InterpolationValue'};`)
    .join('\n');
  return [`  ${JSON.stringify(key)}: {\n${fields}\n  };`];
});

const output = `// Generated by scripts/generate-i18n-types.mjs. Do not edit manually.\n\n`
  + `export type InterpolationValue = string | number | boolean | Date;\n\n`
  + `export type TranslationKey =\n${keys};\n\n`
  + `export type TranslationParamsByKey = {\n${parameterRecords.join('\n')}\n};\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error('Generated i18n types are stale. Run: npm run i18n:types');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, output);
}
